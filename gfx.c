void updateAllSpritesXY() {
    byte msb = 0;
    for (byte t = 0; t < 8; t++) {
        word x = spriteXArray[t];
        if (x < 24)  x = 24;
        if (x > 344) x = 344;
        spriteXArray[t] = x;
        VIC[0x00 + t*2] = (byte)(x & 0xFF);
        VIC[0x01 + t*2] = spriteYArray[t];
        if (x > 255) msb |= (1 << t);
    }
    VIC[0x10] = msb;
}